//! Host component illustrating independent, volatile consumer streams.
//!
//! Compile with `cargo check -p ic-entropy-ic --example consumer_owned --features buffered`.
//! This is a library example: integrate its functions into the host's existing
//! lifecycle and update handlers. It exports no canister endpoints and starts
//! no timers merely by being linked. Budgets are illustrative operational limits,
//! not security ratings. These streams cannot serve fresh-after-commitment needs.

use ic_entropy::Generator;
use ic_entropy_ic::{self as entropy, Error};
use std::cell::RefCell;

/// Separate consumers, each with exclusive stream ownership and its own budget.
#[derive(Clone, Copy)]
pub enum Consumer {
    /// Expand each independently acquired seed into at most 2,000 output bytes.
    Small,
    /// Expand each independently acquired seed into at most 20,000 output bytes.
    Large,
}

impl Consumer {
    const fn index(self) -> usize {
        match self {
            Self::Small => 0,
            Self::Large => 1,
        }
    }

    const fn budget(self) -> u64 {
        match self {
            Self::Small => 2_000,
            Self::Large => 20_000,
        }
    }
}

// No seeds or generators belong in stable memory or a serialized host snapshot.
thread_local! {
    static STREAMS: RefCell<[Option<Generator>; 2]> = const { RefCell::new([None, None]) };
}

// Core Generator has no IC admission policy, including after it has been seeded.
fn require_update_context() -> Result<(), Error> {
    #[cfg(target_arch = "wasm32")]
    if ic_platform_runtime::ic0::in_replicated_execution() != 0 {
        return Ok(());
    }
    Err(Error::NonReplicated)
}

fn discard_streams() {
    STREAMS.with_borrow_mut(|streams| *streams = [None, None]);
}

/// Reconstruct after the host has restored its complete shared timer provider.
///
/// Call from the existing synchronous init/post-upgrade lifecycle participant.
/// A supported snapshot restore must reconstruct the whole provider first;
/// this function alone does not make arbitrary captured heaps safe to resume.
///
/// # Errors
/// Refuses non-replicated execution or returns the adapter's scheduling error.
/// Caller-owned streams are discarded before adapter reconstruction is attempted.
pub fn reconstruct() -> Result<(), Error> {
    require_update_context()?;
    discard_streams();
    entropy::reconstruct()
}

/// Discard owned streams and suspend acquisition before snapshot or shutdown.
///
/// # Errors
/// Refuses non-replicated execution or returns the adapter's scheduling error.
/// The host must handle suspension failure before proceeding with its lifecycle.
pub fn suspend() -> Result<(), Error> {
    require_update_context()?;
    discard_streams();
    entropy::suspend()
}

/// Fill a small caller-owned buffer, spending only this consumer's budget.
///
/// Retain the generator across calls: an 8-byte draw consumes 8 budget bytes,
/// not a new seed. When insufficient budget remains, acquire a full seed before
/// replacing the stream. Any unused old budget is discarded, never refunded.
/// Empty draws acquire nothing. Each call is limited to 1,024 bytes, below both
/// consumers' per-seed budgets, so every admitted draw fits in a replacement.
///
/// # Errors
/// Query/native and oversized calls refuse before consuming any seed or output.
/// If the pool cannot supply a replacement, propagate its typed error with the
/// output and existing generator unchanged. The host can defer/retry; it must
/// not substitute timestamps, zeros or previously returned bytes.
pub fn fill_bytes(consumer: Consumer, output: &mut [u8]) -> Result<(), Error> {
    require_update_context()?;
    if output.len() > 1_024 {
        return Err(Error::DrawTooLarge);
    }
    if output.is_empty() {
        return Ok(());
    }
    STREAMS.with_borrow_mut(|streams| {
        let stream = &mut streams[consumer.index()];
        let needs_seed = stream
            .as_ref()
            .is_none_or(|generator| generator.remaining_bytes() < output.len() as u64);
        if needs_seed {
            // Acquisition can fail. Do not clear or mutate the old stream first.
            let seed = entropy::take_seed()?;
            match stream {
                Some(generator) => generator.reseed(seed, consumer.budget()),
                None => *stream = Some(Generator::from_seed(seed, consumer.budget())),
            }
        }
        stream
            .as_mut()
            .ok_or(Error::NotReady)?
            .fill_bytes(output)
            .map_err(|_| Error::Exhausted)
    })
}

/// Query-safe budget observation; zero means absent or exhausted, not ready.
///
/// This describes the selected owned stream, unlike the adapter's shared
/// convenience-stream status. No seed or generated bytes are exposed.
pub fn remaining_bytes(consumer: Consumer) -> u64 {
    STREAMS.with_borrow(|streams| {
        streams[consumer.index()]
            .as_ref()
            .map_or(0, Generator::remaining_bytes)
    })
}
